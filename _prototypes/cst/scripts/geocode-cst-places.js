#!/usr/bin/env node
/**
 * Builds data/real/place-labels.js, the "City, Region" label for every unit
 * coordinate in data/real/owners.js.
 *
 * Usage:
 *   node scripts/geocode-cst-places.js [--limit N]
 *
 * CST ships unit coordinates with no address, city or region, so the labels the
 * Location column needs have to be reverse geocoded once and cached. Units are
 * grouped into ~11km cells first, which turns ~12k units into ~4k lookups, and
 * the cache is written as it fills so an interrupted run resumes for free.
 *
 * Needs a Mapbox token, taken from MAPBOX_ACCESS_TOKEN or scripts/cst-env.js.
 */

const fs = require("fs");
const path = require("path");

const CST_DIR = path.resolve(__dirname, "..");
const DATA_FILE = path.join(CST_DIR, "data", "real", "owners.js");
const OUT_FILE = path.join(CST_DIR, "data", "real", "place-labels.js");
const ENV_FILE = path.resolve(CST_DIR, "..", "..", "scripts", "cst-env.js");

const CONCURRENCY = 8;
const MAX_ATTEMPTS = 4;
const RETRY_BASE_MS = 500;
const PROGRESS_EVERY = 250;
const SAVE_EVERY = 250;

// Must stay identical to the key data/real/overlay.js builds in the browser.
function getLocationCellKey(lat, lng) {
  return `${lat.toFixed(1)},${lng.toFixed(1)}`;
}

function readGeneratedGlobal(file, globalName) {
  if (!fs.existsSync(file)) return null;

  const source = fs.readFileSync(file, "utf8");
  const assignment = source.indexOf(globalName);
  if (assignment === -1) return null;

  const start = source.indexOf("{", assignment);
  const end = source.lastIndexOf("}");
  if (start === -1 || end <= start) return null;

  return JSON.parse(source.slice(start, end + 1));
}

function getMapboxToken() {
  if (process.env.MAPBOX_ACCESS_TOKEN) return process.env.MAPBOX_ACCESS_TOKEN;
  if (!fs.existsSync(ENV_FILE)) return "";

  const match = fs.readFileSync(ENV_FILE, "utf8").match(/MAPBOX_ACCESS_TOKEN:\s*"([^"]+)"/);
  return match ? match[1] : "";
}

// One representative real coordinate per cell: a cell centre can land offshore.
function collectCells(dumpData) {
  const cells = new Map();

  (dumpData.owners || []).forEach((owner) => {
    (owner.units || []).forEach(([lat, lng]) => {
      if (!Number.isFinite(lat) || !Number.isFinite(lng)) return;

      const key = getLocationCellKey(lat, lng);
      if (!cells.has(key)) cells.set(key, [lat, lng]);
    });
  });

  return cells;
}

function formatLabel(features) {
  const place = features.find((feature) => feature.properties?.feature_type === "place");
  const region = features.find((feature) => feature.properties?.feature_type === "region");
  const placeName = place?.properties?.name || "";
  const regionName = place?.properties?.context?.region?.name || region?.properties?.name || "";

  if (placeName && regionName) return `${placeName}, ${regionName}`;
  return placeName || regionName || "";
}

async function reverseGeocode(lat, lng, token) {
  const url = "https://api.mapbox.com/search/geocode/v6/reverse"
    + `?longitude=${lng}&latitude=${lat}&types=place,region&access_token=${token}`;

  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt += 1) {
    try {
      const response = await fetch(url);

      if (response.status === 429 || response.status >= 500) {
        await new Promise((resolve) => setTimeout(resolve, RETRY_BASE_MS * 2 ** attempt));
        continue;
      }

      if (!response.ok) throw new Error(`HTTP ${response.status}`);

      const body = await response.json();
      return formatLabel(body.features || []);
    } catch (error) {
      if (attempt === MAX_ATTEMPTS) throw error;
      await new Promise((resolve) => setTimeout(resolve, RETRY_BASE_MS * 2 ** attempt));
    }
  }

  return "";
}

function writeCache(labels) {
  const sorted = Object.keys(labels).sort().reduce((result, key) => {
    result[key] = labels[key];
    return result;
  }, {});

  fs.writeFileSync(
    OUT_FILE,
    `// Generated by scripts/geocode-cst-places.js - do not edit by hand.
// Reverse-geocoded "City, Region" per ~11km coordinate cell, because CST unit
// records carry coordinates only. Keys match data/real/overlay.js.
window.cstDumpLocations = ${JSON.stringify(sorted, null, 2)};
`
  );
}

async function main() {
  const dumpData = readGeneratedGlobal(DATA_FILE, "window.cstDumpData");
  if (!dumpData) {
    console.error(`Could not read ${DATA_FILE}. Run scripts/build-cst-data.js first.`);
    process.exit(1);
  }

  const token = getMapboxToken();
  if (!token) {
    console.error("No Mapbox token. Set MAPBOX_ACCESS_TOKEN or add one to scripts/cst-env.js.");
    process.exit(1);
  }

  const labels = readGeneratedGlobal(OUT_FILE, "window.cstDumpLocations") || {};
  const cells = collectCells(dumpData);
  const limitFlag = process.argv.indexOf("--limit");
  const limit = limitFlag === -1 ? Infinity : Number(process.argv[limitFlag + 1]);
  const pending = [...cells.entries()]
    .filter(([key]) => labels[key] === undefined)
    .slice(0, limit === Infinity ? undefined : limit);

  console.log(`cells: ${cells.size} total, ${Object.keys(labels).length} cached, ${pending.length} to geocode`);
  if (!pending.length) {
    writeCache(labels);
    console.log("DONE nothing to geocode");
    return;
  }

  let completed = 0;
  let failed = 0;
  let cursor = 0;

  async function worker() {
    while (cursor < pending.length) {
      const [key, [lat, lng]] = pending[cursor];
      cursor += 1;

      try {
        labels[key] = await reverseGeocode(lat, lng, token);
      } catch (error) {
        failed += 1;
        console.warn(`failed ${key}: ${error.message}`);
      }

      completed += 1;
      if (completed % SAVE_EVERY === 0) writeCache(labels);
      if (completed % PROGRESS_EVERY === 0) {
        console.log(`geocoded ${completed}/${pending.length}`);
      }
    }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  writeCache(labels);

  const empty = Object.values(labels).filter((label) => !label).length;
  console.log(`DONE geocoded=${completed} failed=${failed} cached=${Object.keys(labels).length} empty=${empty}`);
}

main();
